#!/usr/bin/env node
/**
 * Build the small, auditable bridge between the existing CET4 pool and the
 * imported packs.  A candidate is reusable only when its exact
 * Chinese/English/POS id already exists in CET4's approved pool and in the
 * target pack.  Context matching remains the tokenizer's responsibility.
 *
 * The script emits aggregate counts plus TypeScript arrays; it never reads
 * novel text or quality labels.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mapDir = resolve(root, "src/data");
const output = resolve(mapDir, "shared-vocabulary-candidates.ts");
const report = resolve(mapDir, "import-reports/shared-candidate-reuse.report.json");

const names = ["cet4", "cet6", "ielts", "toefl"];
const maps = Object.fromEntries(await Promise.all(names.map(async (name) => {
  const raw = JSON.parse(await readFile(resolve(mapDir, `${name}-map.json`), "utf8"));
  const rows = Array.isArray(raw) ? raw : raw.entries ?? raw.words ?? Object.values(raw);
  return [name, rows];
})));

const candidateId = (entry) => `${String(entry.zh ?? "").trim()}:${String(entry.en ?? "").trim()}:${String(entry.partOfSpeech ?? "").trim()}`;
const idsFor = (rows) => new Set(rows.map(candidateId).filter((id) => !id.startsWith(":") && !id.endsWith(":")));
const mapIds = Object.fromEntries(names.map((name) => [name, idsFor(maps[name])]));
const source = await readFile(resolve(mapDir, "approved-candidates.ts"), "utf8");
const cet4Approved = new Set((source.match(/"[^"\n]+:[^"\n]+:[^"\n]+"/g) ?? []).map((value) => value.slice(1, -1)));
const groupedByZh = Object.fromEntries(names.map((name) => {
  const groups = new Map();
  for (const entry of maps[name]) {
    const values = groups.get(entry.zh) ?? [];
    values.push(candidateId(entry));
    groups.set(entry.zh, values);
  }
  return [name, groups];
}));

const reusable = {};
for (const name of names.slice(1)) reusable[name] = [...mapIds[name]].filter((id) => cet4Approved.has(id)).sort();
const reusableSingleSense = {};
for (const name of names.slice(1)) {
  reusableSingleSense[name] = reusable[name].filter((id) => {
    const [zh] = id.split(":", 1);
    return (groupedByZh[name].get(zh) ?? []).length === 1
      && (groupedByZh.cet4.get(zh) ?? []).length === 1
      && zh.length <= 4
      && !/[《》·（）()\s—–-]/.test(zh);
  });
}
const importedSets = names.slice(1).map((name) => mapIds[name]);
const importedUnion = new Set(importedSets.flatMap((set) => [...set]));
const crossImportedPackOverlap = {
  atLeastTwoPacks: [...importedUnion].filter((id) => importedSets.filter((set) => set.has(id)).length >= 2).length,
  allThreePacks: [...importedUnion].filter((id) => importedSets.every((set) => set.has(id))).length,
};

const quote = (id) => JSON.stringify(id);
const lines = [
  "/* Generated by scripts/build-shared-candidate-reuse.mjs; do not edit by hand. */",
  "/* Exact CET4 lexical approvals only. Per-occurrence context and boundary checks still apply. */",
];
for (const name of names.slice(1)) {
  const constant = `${name.toUpperCase()}_CET4_REUSABLE_IDS`;
  lines.push(`export const ${constant} = [`);
  for (const id of reusable[name]) lines.push(`  ${quote(id)},`);
  lines.push("] as const;", "");
  const singleConstant = `${name.toUpperCase()}_CET4_REUSABLE_SINGLE_SENSE_IDS`;
  lines.push(`export const ${singleConstant} = [`);
  for (const id of reusableSingleSense[name]) lines.push(`  ${quote(id)},`);
  lines.push("] as const;", "");
}
await writeFile(output, `${lines.join("\n")}\n`, "utf8");
await writeFile(report, `${JSON.stringify({
  schemaVersion: 1,
  rule: "exact candidateId (zh:en:partOfSpeech) in CET4 approved pool and target map",
  cet4ApprovedCount: cet4Approved.size,
  datasets: Object.fromEntries(names.map((name) => [name, {
    uniqueCandidates: mapIds[name].size,
    reusableFromCet4: name === "cet4" ? cet4Approved.size : reusable[name].length,
    reusableSingleSense: name === "cet4" ? null : reusableSingleSense[name].length,
    remainingUnique: name === "cet4" ? null : mapIds[name].size - reusable[name].length,
  }])),
  crossImportedPackOverlap,
  output: "src/data/shared-vocabulary-candidates.ts",
}, null, 2)}\n`, "utf8");
console.log(JSON.stringify({ output, report, reusableFromCet4: Object.fromEntries(Object.entries(reusable).map(([name, ids]) => [name, ids.length])), reusableSingleSense: Object.fromEntries(Object.entries(reusableSingleSense).map(([name, ids]) => [name, ids.length])) }, null, 2));
