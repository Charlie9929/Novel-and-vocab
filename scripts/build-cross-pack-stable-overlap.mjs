#!/usr/bin/env node
/**
 * Build a conservative cross-pack coverage overlay.
 *
 * A tuple is admitted to a target pack only when it is already a stable,
 * approved tuple in at least two of the other imported packs, exists in the
 * target map with one sense, and is not blocked/contextual in the target.
 * This is deliberately metadata-only: no novel text or quality labels are
 * read. Existing target-specific approvals remain the source of truth for
 * ambiguous and contextual terms.
 */
import { build } from "esbuild";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src/data/cross-pack-stable-overlap.ts");
const reportPath = resolve(root, "src/data/import-reports/cross-pack-stable-overlap.report.json");
const vocabularyIds = ["cet4", "cet6", "kaoyan", "ielts", "toefl"];
// CET4 is the established baseline pack. New CET4 entries still require its
// own lexical review; only the imported target packs use this bridge.
const targetVocabularyIds = ["cet6", "kaoyan", "ielts", "toefl"];

const bundle = await build({
  stdin: {
    contents: `
      import { candidateModeForVocabulary, getVocabularyCandidateStrategy, isCandidateApprovedForVocabulary } from ${JSON.stringify(resolve(root, "src/data/vocabulary-candidates.ts"))};
      import { loadVocabularyEntries } from ${JSON.stringify(resolve(root, "src/data/vocabulary.ts"))};
      export { candidateModeForVocabulary, getVocabularyCandidateStrategy, isCandidateApprovedForVocabulary, loadVocabularyEntries };
    `,
    resolveDir: root,
    sourcefile: "cross-pack-stable-overlap-entry.ts",
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  write: false,
});

const temporary = await mkdtemp(join(tmpdir(), "immersive-cross-pack-overlap-"));
const bundledPath = join(temporary, "entry.mjs");
try {
  await writeFile(bundledPath, bundle.outputFiles[0].text, "utf8");
  const module = await import(pathToFileURL(bundledPath).href);
  const entriesByVocabulary = new Map();
  for (const vocabularyId of vocabularyIds) {
    entriesByVocabulary.set(vocabularyId, await module.loadVocabularyEntries(vocabularyId));
  }

  const generatedOverlay = await readExistingOverlay(outputPath);
  const approvedByVocabulary = new Map(vocabularyIds.map((vocabularyId) => {
    const overlay = new Set(generatedOverlay[vocabularyId] ?? []);
    const approved = new Set([...module.getVocabularyCandidateStrategy(vocabularyId).approvedCandidateIds]
      .filter((candidateId) => !overlay.has(candidateId))
      .filter((candidateId) => module.isCandidateApprovedForVocabulary(vocabularyId, candidateId)));
    return [vocabularyId, approved];
  }));

  const entriesByTerm = new Map(vocabularyIds.map((vocabularyId) => {
    const grouped = new Map();
    for (const entry of entriesByVocabulary.get(vocabularyId)) {
      const candidateId = candidateIdFor(entry);
      grouped.set(entry.zh, [...(grouped.get(entry.zh) ?? []), candidateId]);
    }
    return [vocabularyId, grouped];
  }));

  const overlay = Object.fromEntries(vocabularyIds.map((vocabularyId) => [vocabularyId, []]));
  for (const vocabularyId of targetVocabularyIds) {
    const otherVocabularyIds = vocabularyIds.filter((id) => id !== vocabularyId);
    const targetEntries = entriesByVocabulary.get(vocabularyId);
    const targetApproved = approvedByVocabulary.get(vocabularyId);
    const candidates = new Set();
    for (const entry of targetEntries) {
      const candidateId = candidateIdFor(entry);
      const termCandidates = entriesByTerm.get(vocabularyId).get(entry.zh) ?? [];
      if (termCandidates.length !== 1) continue;
      if (targetApproved.has(candidateId)) continue;
      if (module.candidateModeForVocabulary(vocabularyId, candidateId) !== "stable") continue;
      if (!/^[一-鿿]{2,4}$/u.test(entry.zh)) continue;
      if (!/^[A-Za-z][A-Za-z -]*$/u.test(entry.en)) continue;
      if (!new Set(["noun", "verb", "adjective", "adverb"]).has(entry.partOfSpeech)) continue;

      const stableSupporters = otherVocabularyIds.filter((otherVocabularyId) =>
        approvedByVocabulary.get(otherVocabularyId).has(candidateId)
        && module.candidateModeForVocabulary(otherVocabularyId, candidateId) === "stable");
      if (stableSupporters.length < 2) continue;
      candidates.add(candidateId);
    }
    overlay[vocabularyId] = [...candidates].sort((left, right) => left.localeCompare(right, "zh-CN"));
  }

  const quote = (value) => JSON.stringify(value);
  const lines = [
    "/* Generated by scripts/build-cross-pack-stable-overlap.mjs; do not edit by hand. */",
    "/* Stable exact tuples approved in at least two other packs and single-sense in the target pack. */",
  ];
  for (const vocabularyId of vocabularyIds) {
    const constant = `${vocabularyId.toUpperCase()}_CROSS_PACK_STABLE_OVERLAP_IDS`;
    lines.push(`export const ${constant} = [`);
    for (const candidateId of overlay[vocabularyId]) lines.push(`  ${quote(candidateId)},`);
    lines.push("] as const;", "");
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, `${lines.join("\n").replace(/\n+$/, "")}\n`, "utf8");
  await mkdir(dirname(reportPath), { recursive: true });
  await writeFile(reportPath, `${JSON.stringify({
    schemaVersion: 1,
    rule: "target has one sense; exact tuple is stable-approved in at least two other vocabulary packs; target mode is stable",
    sourcePolicy: "pinned vocabulary metadata only; no novel text or quality labels",
    generatedOverlaySource: "src/data/cross-pack-stable-overlap.ts",
    counts: Object.fromEntries(vocabularyIds.map((vocabularyId) => [vocabularyId, overlay[vocabularyId].length])),
  }, null, 2)}\n`, "utf8");
  console.log(JSON.stringify({ output: outputPath, report: reportPath, counts: Object.fromEntries(vocabularyIds.map((vocabularyId) => [vocabularyId, overlay[vocabularyId].length])) }, null, 2));
} finally {
  await rm(temporary, { recursive: true, force: true });
}

async function readExistingOverlay(path) {
  if (!existsSync(path)) return {};
  const source = await readFile(path, "utf8");
  const result = {};
  for (const vocabularyId of vocabularyIds) {
    const constant = `${vocabularyId.toUpperCase()}_CROSS_PACK_STABLE_OVERLAP_IDS`;
    const match = source.match(new RegExp(`export const ${constant} = \\[([\\s\\S]*?)\\] as const;`));
    result[vocabularyId] = [...(match?.[1]?.matchAll(/"([^"\n]+)"/g) ?? [])].map((item) => item[1]);
  }
  return result;
}

function candidateIdFor(entry) {
  return `${entry.zh}:${entry.en}:${entry.partOfSpeech}`;
}
