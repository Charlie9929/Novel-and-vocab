#!/usr/bin/env node
/** Export lexical-review decisions without copying any novel/context data. */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i], process.argv[i + 1]);
const outputPath = resolve(args.get("--out") ?? "src/data/overlap-reviewed-candidates.ts");
const names = ["cet6", "ielts", "toefl"];
const reviews = Object.fromEntries(await Promise.all(names.map(async (name) => {
  const path = resolve(args.get(`--${name}`) ?? `tests/private-input/quality/overlap-review-${name}.json`);
  const review = JSON.parse(await readFile(path, "utf8"));
  if (!Array.isArray(review.safeLexicalReuse) || !Array.isArray(review.needsContext) || !Array.isArray(review.rejectLexical)) {
    throw new Error(`Invalid lexical review for ${name}`);
  }
  return [name, review];
})));

const lines = [
  "/* Generated by scripts/export-overlap-review-candidates.mjs. */",
  "/* Lexical review only; target-pack occurrence/context gates still apply. */",
];
for (const name of names) {
  lines.push(`export const ${name.toUpperCase()}_OVERLAP_LEXICAL_SAFE_IDS = [`);
  for (const id of [...new Set(reviews[name].safeLexicalReuse)].sort((a, b) => a.localeCompare(b, "zh-CN"))) {
    lines.push(`  ${JSON.stringify(id)},`);
  }
  lines.push("] as const;", "");
}
await writeFile(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(JSON.stringify(Object.fromEntries(names.map((name) => [name, {
  safeLexicalReuse: reviews[name].safeLexicalReuse.length,
  needsContext: reviews[name].needsContext.length,
  rejectLexical: reviews[name].rejectLexical.length,
}]))));
