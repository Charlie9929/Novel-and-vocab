#!/usr/bin/env node
/**
 * Build the small candidate-policy index from the reviewed CET4 ids and the
 * imported pack maps. The full vocabulary JSON stays lazy-loaded at runtime;
 * this generated intersection is all the policy module needs at startup.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const approvedSource = fs.readFileSync(path.join(root, "src/data/approved-candidates.ts"), "utf8");
const approvedIds = new Set(
  [...approvedSource.matchAll(/"([^"\n]+:[^"\n]+:(?:noun|verb|adjective|adverb))"/g)].map((match) => match[1]),
);

const packs = [
  ["cet6", "CET6_IMPORTED_APPROVED_IDS"],
  ["ielts", "IELTS_IMPORTED_APPROVED_IDS"],
  ["toefl", "TOEFL_IMPORTED_APPROVED_IDS"],
];
const lines = [
  "/* Generated by scripts/build-vocabulary-approved-index.mjs; do not edit by hand. */",
  "",
];

for (const [pack, exportName] of packs) {
  const entries = JSON.parse(fs.readFileSync(path.join(root, `src/data/${pack}-map.json`), "utf8"));
  const ids = entries
    .map((entry) => `${entry.zh}:${entry.en}:${entry.partOfSpeech}`)
    .filter((id) => approvedIds.has(id))
    .sort((left, right) => left.localeCompare(right, "en"));
  lines.push(`export const ${exportName} = new Set<string>([`);
  for (const id of ids) lines.push(`  ${JSON.stringify(id)},`);
  lines.push("]);", "");
  console.log(`${pack}: ${ids.length} imported approved candidates`);
}

fs.writeFileSync(path.join(root, "src/data/vocabulary-approved-index.ts"), `${lines.join("\n")}\n`);
